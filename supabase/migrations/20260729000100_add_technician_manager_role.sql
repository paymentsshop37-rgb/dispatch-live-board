create or replace function public.protect_technician_lifecycle_fields()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'DELETE' then
    raise exception 'Permanent technician deletion is disabled';
  end if;
  if (old.is_active is distinct from new.is_active
      or old.deleted_at is distinct from new.deleted_at
      or old.deleted_by is distinct from new.deleted_by)
     and not public.can_manage_technicians() then
    raise exception 'Technician management access required';
  end if;
  return new;
end;
$$;

