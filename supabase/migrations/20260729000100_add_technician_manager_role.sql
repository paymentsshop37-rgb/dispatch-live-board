drop policy if exists "only admins may delete technicians" on public.technicians;

create policy "operational roles read active technicians"
  on public.technicians for select to authenticated
  using (is_active = true and public.can_view_active_technicians());

create policy "technician managers read all technicians"
  on public.technicians for select to authenticated
  using (public.can_manage_technicians());

create policy "technician managers insert technicians"
  on public.technicians for insert to authenticated
  with check (public.can_manage_technicians());

create policy "technician managers update technicians"
  on public.technicians for update to authenticated
  using (public.can_manage_technicians())
  with check (public.can_manage_technicians());

grant select, insert, update on public.technicians to authenticated;
revoke delete on public.technicians from authenticated;

