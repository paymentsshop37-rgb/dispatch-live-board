// Input: unzipped official 2025 National Places Gazetteer (pipe-delimited).
// Download: https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2025_Gazetteer/2025_Gaz_place_national.zip
import fs from 'node:fs';
import crypto from 'node:crypto';

const input = process.argv[2];
if (!input) throw new Error('Pass the path to 2025_Gaz_place_national.txt');
const source = fs.readFileSync(input, 'utf8');
const [header, ...lines] = source.trim().split(/\r?\n/);
const columns = header.split('|').map(s => s.trim());
const suffix = / (?:city and borough|consolidated government|metropolitan government|unified government|urban county|municipality|corporation|borough|city|town|village|CDP|comunidad|zona urbana)$/;
const cities = lines.map(line => {
  const row = Object.fromEntries(line.split('|').map((v, i) => [columns[i], v.trim()]));
  const city = row.NAME.replace(/ \(balance\)$/, '').replace(suffix, '');
  const latitude = Number(row.INTPTLAT), longitude = Number(row.INTPTLONG);
  if (!city || !/^[A-Z]{2}$/.test(row.USPS) || !row.INTPTLAT || !row.INTPTLONG || !Number.isFinite(latitude) || !Number.isFinite(longitude) || Math.abs(latitude) > 90 || Math.abs(longitude) > 180) throw new Error(`Invalid place ${row.GEOID}`);
  return { city, state: row.USPS, latitude, longitude };
}).filter(row => row.state !== 'PR'); // 50 states + DC; Puerto Rico is not a state.
if (cities.length < 30000) throw new Error('Incomplete national catalog');
const digest = crypto.createHash('sha256').update(source).digest('hex');
const sql = `-- Generated by scripts/build-nearby-city-catalog.mjs. Do not hand-edit cities.
-- U.S. Census Bureau, 2025 National Places Gazetteer; 50 states + DC.
-- Source: https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2025_Gazetteer/2025_Gaz_place_national.zip
-- Input SHA256: ${digest}; ${cities.length} places. Coordinates: Census internal points.
-- Versioned reference data in a function; no new table and no external runtime API.
create or replace function public.us_nearby_city_catalog()
returns table(city text, state text, latitude numeric, longitude numeric)
language sql immutable parallel safe
set search_path = public
as $catalog$
  select * from jsonb_to_recordset($places$${JSON.stringify(cities)}$places$::jsonb)
    as place(city text, state text, latitude numeric, longitude numeric);
$catalog$;
revoke all on function public.us_nearby_city_catalog() from public, anon, authenticated;
`;
fs.writeFileSync('supabase/migrations/20260909000100_us_nearby_city_catalog.sql', sql);
console.log(JSON.stringify({ places: cities.length, sha256: digest }));
